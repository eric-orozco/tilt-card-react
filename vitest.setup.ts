import { vi } from 'vitest';

/**
 * motion/react's useReducedMotion calls window.matchMedia internally.
 * jsdom does not implement matchMedia, so we provide a lightweight stub.
 */
Object.defineProperty(window, 'matchMedia', {
  writable: true,
  value: vi.fn().mockImplementation((query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: vi.fn(),
    removeListener: vi.fn(),
    addEventListener: vi.fn(),
    removeEventListener: vi.fn(),
    dispatchEvent: vi.fn(),
  })),
});
